def test_the_two_scripts_that_fit_the_same_model_agree_in_print():
    """ablate.py and volume_feature.py fit the same model on the same split and
    each publish an F1 for it. They agree to three decimals but NOT bit for bit -
    0.9774011299435029 against ...28 - because one computes 2PR/(P+R) directly and
    the other goes through sklearn. Compare what is printed, not the float."""
    data = tables.load()
    ablation = data["ablation"]["results"]
    volume = data["volume"]
    tabulated = volume["policies"][volume["tabulated"]]
    for there, here in ((data["ablation"]["reference"], volume["order"][0]),
                        (data["ablation"]["shipped"], volume["shipped"])):
        mine, theirs = ablation[there]["f1"], tabulated[here]["f1"]
        assert f"{mine:.3f}" == f"{theirs:.3f}", (there, here, mine, theirs)
        assert abs(mine - theirs) < 1e-9, (there, here, mine, theirs)

