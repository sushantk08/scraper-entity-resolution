"""The drift test. Fails when README.md's generated tables disagree with tables.py.

WHAT THIS DOES NOT DO: re-run the sweep. It compares the committed README against
the runs recorded under results/, so it catches a hand-edited table, a stale table, and a regenerated
sweep whose README was never updated. It cannot catch a wrong sweep - test_resolve.py
and test_decide.py cover the code that produced those numbers.

test_the_drift_test_can_actually_fail is the one to keep alive. A comparison test that
compares nothing passes forever, which is exactly how the first closure audit got
shipped.
"""
import io

import pytest

import tables


def readme():
    return io.open(tables.README, encoding="utf-8").read()


def prose():
    """The README with every run of whitespace collapsed. A claim in the prose can
    sit either side of a line break - these paragraphs are hand-wrapped and rewrap
    whenever a word changes - so a literal substring search is not stable. Tables
    are still compared against readme() verbatim, where the layout is the point.
    """
    return " ".join(readme().split())


def block(name, table):
    return f"<!-- generated by tables.py: {name} -->\n{table}\n{tables.END}"


def test_every_generated_block_appears_in_the_readme_verbatim():
    text = readme()
    for name, table in tables.blocks(tables.load()):
        assert text.count(block(name, table)) == 1, (
            f"README.md's {name} table disagrees with tables.py - "
            f"run: python tables.py --write"
        )


def test_the_drift_test_can_actually_fail():
    """Move one recorded number and the block must stop matching. If blocks() returned
    nothing, or rendered from the README rather than the sweep, the test above would
    pass unconditionally and prove nothing at all."""
    recorded = tables.load()
    sweep = recorded["sweep"]
    sweep["results"][sweep["write_policy"]][0]["f1"] = 0.5
    changed = dict(tables.blocks(recorded))["policy-comparison"]
    assert changed not in readme()


def test_there_is_a_block_for_every_table_the_readme_marks_as_generated():
    assert len(tables.blocks(tables.load())) == readme().count(tables.END) == 10


def test_a_rendered_table_is_aligned():
    """Column widths are computed over the header and every row, so each line of a
    table is the same length. Checked here because a terminal paste cannot be trusted
    to preserve trailing spaces."""
    for name, table in tables.blocks(tables.load()):
        assert len({len(line) for line in table.split("\n")}) == 1, name


def test_no_merges_reports_a_dash_rather_than_zero_correct():
    """Zero correct out of zero merges is not a finding, it is the definition of a
    matching: closure over one is the identity function. A 0 there would read as
    evidence for the same claim the number cannot speak to."""
    data = tables.load()
    wanted = f"| {tables.DISPLAY[data['sweep']['write_policy']]}"
    table = dict(tables.blocks(data))["closure-cost"]
    row = next(line for line in table.split("\n") if line.startswith(wanted))
    assert row.split("|")[-2].strip() == "-"


def test_a_policy_with_no_readme_name_is_refused(monkeypatch):
    monkeypatch.delitem(tables.DISPLAY, "mutual best")
    with pytest.raises(SystemExit):
        tables.load()


def test_the_marker_path_and_the_header_path_agree():
    """First splice finds a table by a predicate on its header row; the second finds
    the markers the first one left. Two code paths, and if they disagreed the drift
    test would fail on every run for a reason unrelated to any number."""
    table = "| policy | x |\n|--------|---|\n| a      | b |"
    lines = ["intro", "| policy | old |", "|--------|-----|", "| a | old |", "outro"]

    def matches(line):
        return line.startswith("| policy")

    once = tables.splice(lines, "demo", table, matches)
    assert tables.splice(once, "demo", table, matches) == once
    assert (once[0], once[-1]) == ("intro", "outro")


def test_two_candidate_headers_are_refused():
    with pytest.raises(SystemExit):
        tables.splice(
            ["| policy | a |", "| policy | b |"], "demo", "x",
            lambda line: line.startswith("| policy"),
        )


def cell_named(table, name):
    """First column matched exactly. "all features" is a prefix of "all features +
    volume veto", so startswith would pick the wrong row."""
    return next(l for l in table.split("\n") if l.split("|")[1].strip() == name)


def test_the_ablation_delta_is_measured_before_rounding():
    data = tables.load()
    recorded = data["ablation"]
    reference = recorded["results"][recorded["reference"]]["f1"]
    shipped = recorded["results"][recorded["shipped"]]["f1"]
    honest = f"{shipped - reference:+.3f}"
    naive = f"{round(shipped, 3) - round(reference, 3):+.3f}"
    assert honest != naive, "this data can no longer tell the two apart"
    table = dict(tables.blocks(data))["ablation"]
    row = cell_named(table, tables.FEATURE_SETS[recorded["shipped"]])
    assert row.split("|")[-2].strip() == honest


